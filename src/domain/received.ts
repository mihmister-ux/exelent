import { formatRu } from "@/lib/dates";

/**
 * Подпись «когда привезли партию» для плашки товара.
 *
 * Дата поступления — это то, что отличает две приёмки одного и того же товара
 * с одним сроком годности. Если её нет, плашка говорит об этом прямо:
 * пустое место на этом месте читалось бы как «привезли сегодня».
 *
 * Нераспознанная дата (не YYYY-MM-DD) — тоже «не указано»: показать «—»
 * рядом со словом «Поступление» значило бы соврать про формат.
 */
export function receivedLabel(value?: string | null): string {
  const day = formatRu(value);
  return day === "—" ? "Поступление не указано" : `Поступление: ${day}`;
}

/** Короткая форма для строк, где уже есть разделители «·». */
export function receivedShort(value?: string | null): string {
  const day = formatRu(value);
  return day === "—" ? "поступление не указано" : `поступление ${day}`;
}
