/**
 * Разбор названия поставщика: где в строке «ядро» имени, а где реквизиты.
 *
 * Один и тот же поставщик приходит в базу тремя путями, и каждый раз выглядит
 * по-своему:
 *
 *   лист Excel     «ГРИНФИТО ООО»
 *   накладная      «Общество с ограниченной ответственностью "РИФ И КО",
 *                   ИНН 0400001746, КПП 040001001, 649002, Алтай респ, ул. …»
 *   рука человека  «Гринфито»
 *
 * Для журнала это один поставщик с ядром «Гринфито». `cleanSupplierName`
 * достаёт ядро, `supplierNameKey` даёт ключ, по которому написания
 * сравниваются между собой, а `hasSupplierNoise` отвечает на вопрос «в этом
 * имени есть мусор?» — им пользуется очистка базы.
 *
 * ГРАБЛИ, которые здесь уже стоили дублей в справочнике: в JavaScript `\b`
 * считается по `\w`, то есть по латинице и цифрам. Для кириллицы «ООО» в конце
 * «ГРИНФИТО ООО» НЕ образует границу слова, поэтому `/\bооо\b/` не находил
 * ничего: «ГРИНФИТО ООО» давало ключ `гринфито ооо`, «Гринфито» — `гринфито`,
 * и один поставщик честно считался двумя. Границы задаём явно: слева — начало
 * строки или не-буква, справа — не-буква.
 */

/** Слева: начало строки или любой символ, кроме буквы и цифры. */
const BEFORE = String.raw`(?:^|[^\p{L}\p{N}])`;
/** Справа: ни буквы, ни цифры. Хвост для имён — граница строгая. */
const AFTER = String.raw`(?![\p{L}\p{N}])`;
/** Хвост для реквизитов мягче: за «ИНН» идёт цифра, за «тел» — точка. */
const AFTER_MARKER = String.raw`(?![\p{L}])`;

/**
 * Организационно-правовые формы целиком. Убираем ДО аббревиатур: иначе от
 * «Общество с ограниченной ответственностью» осталось бы «с ограниченной
 * ответственностью».
 */
const FULL_FORMS: readonly string[] = [
  "общество с ограниченной ответственностью",
  "общество с дополнительной ответственностью",
  "закрытое акционерное общество",
  "открытое акционерное общество",
  "публичное акционерное общество",
  "акционерное общество",
  "индивидуальный предприниматель",
  "производственный кооператив",
  "сельскохозяйственный производственный кооператив",
  "унитарное предприятие",
  "торговый дом",
  "производственно-коммерческая фирма",
  "производственная коммерческая фирма",
  "научно-производственное объединение",
];

/** Сокращения форм: «ООО», «ПКФ», «ИП». Отдельным словом, не частью названия. */
const ABBREVIATIONS: readonly string[] = [
  "ооо", "оао", "зао", "пао", "ао", "ип", "нко", "пкф", "пко", "тд", "тк", "гк", "спк",
];

/**
 * Слова-маркеры реквизитов: с первого из них имя поставщика заканчивается.
 * Латинские варианты — так печатает счёт зарубежного поставщика.
 */
const MARKER_WORDS: readonly string[] = [
  "ИНН", "КПП", "ОГРН", "ОГРНИП", "ОКПО", "ОКВЭД", "ОКТМО",
  "INN", "KPP", "OGRN", "VAT",
  "адрес", "address",
  "тел", "телефон", "phone", "факс", "fax", "моб",
  "e-mail", "email", "сайт", "site", "www",
  "р/с", "к/с", "бик",
];

/** Сокращения адреса с точкой: «г. Москва», «ул. Ленина». Без точки не трогаем. */
const ADDRESS_PARTS: readonly string[] = [
  "г", "ул", "д", "кв", "оф", "офис", "обл", "респ", "пер", "наб", "стр", "корп",
  "пом", "этаж", "шоссе", "бул", "б-р", "пр-т", "проезд", "туп", "аллея", "литер", "а/я",
];

/** Реквизитный маркер: с него имя заканчивается, дальше идут ИНН и адрес. */
const MARKER = new RegExp(`${BEFORE}(?:${MARKER_WORDS.join("|")})${AFTER_MARKER}`, "iu");

/** Почтовый индекс: шесть цифр отдельным числом. */
const POSTAL_INDEX = new RegExp(String.raw`(?:^|\s)\d{6}(?!\d)`, "u");

/** Реквизитный номер: семь и более цифр подряд (ИНН 10, КПП 9, ОГРН 13, телефон). */
const LONG_DIGITS = /\d(?:[\s()-]*\d){6,}/u;

/** Обрывок имени листа Excel: «ЛБренд Кавказский травник (ист1». */
const SHEET_TRUNCATION = /\(\s*(?:ист|лист)\d*\)?/giu;

/**
 * Адресная часть: «г. Москва», «ул. Ленина», «обл. Тверская».
 *
 * Требуем точку И следующее за ней слово с заглавной буквы. Иначе «д. 5»
 * считалось бы адресом, а «ООО Г. Радуга» потеряло бы начало имени.
 *
 * Это ГРАНИЦА имени, а не то, что вырезается: адрес в накладной идёт после
 * названия («Ромашка, г. Москва, ул. Ленина»), поэтому всё от первой адресной
 * части отбрасывается целиком. Вырезание по отдельности оставляло в имени
 * огрызки «Москва Ленина д 5».
 */
const ADDRESS_PART = new RegExp(
  `${BEFORE}(?:${ADDRESS_PARTS.join("|")})\\.\\s*\\p{Lu}`,
  "iu",
);

/** Годится ли имя для справочника как есть — или в нём мусор. */
const NOISE = new RegExp(
  [
    `${BEFORE}(?:${FULL_FORMS.join("|")})${AFTER}`,
    `${BEFORE}(?:${ABBREVIATIONS.join("|")})${AFTER}`,
    `${BEFORE}(?:${MARKER_WORDS.join("|")})${AFTER_MARKER}`,
    String.raw`(?:^|\s)\d{6}(?!\d)`,
    String.raw`\d(?:[\s()-]*\d){6,}`,
    String.raw`\(\s*(?:ист|лист)\d*`,
  ].join("|"),
  "iu",
);


/** Инициалы в хвосте: «ИП Иванов И.И.» → «Иванов». */
const TRAILING_INITIALS = new RegExp(String.raw`(?:\s|^)[\p{Lu}]\.(?:\s*[\p{Lu}]\.)*\s*$`, "u");

/** Служебные слова, которые внутри имени остаются строчными: «Риф и Ко». */
const SMALL_WORDS = new Set([
  "и", "в", "во", "на", "с", "со", "о", "об", "от", "до", "по", "за", "для", "при", "у", "к", "не",
]);

/** Схлопывает пробелы и обрезает висящие разделители. */
function tidy(text: string): string {
  return text
    .replace(/[.,;:()[\]{}]+/g, " ")
    .replace(/[\s\-–—/|+*]+$/u, " ")
    .replace(/^[\s\-–—/|+*,]+/u, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Докуда доходит имя: индекс первого реквизита, адресной части, индекса или
 * длинного числа. Возвращает -1, если ничего такого нет.
 */
function requisitesStart(text: string): number {
  const at = [
    MARKER.exec(text)?.index,
    ADDRESS_PART.exec(text)?.index,
    POSTAL_INDEX.exec(text)?.index,
    LONG_DIGITS.exec(text)?.index,
  ].filter((index): index is number => typeof index === "number");

  return at.length > 0 ? Math.min(...at) : -1;
}

/** Убирает перечисленные слова, стоящие отдельными словами. */
function removeWords(text: string, words: readonly string[]): string {
  if (words.length === 0) return text;
  return text.replace(new RegExp(`${BEFORE}(?:${words.join("|")})${AFTER}`, "giu"), " ");
}

/** Все буквы заглавные? «ГРИНФИТО» — да, «ЛБренд» — нет. */
function isShouty(text: string): boolean {
  const letters = text.match(/\p{L}/gu) ?? [];
  if (letters.length === 0) return false;
  // Достаточно одной строчной буквы: «ЛБренд» и «Риф и Ко» человек уже написал сам.
  return !letters.some((char) => char === char.toLocaleLowerCase("ru"));
}

/**
 * Приводит КАПС к нормальному виду: «ГРИНФИТО» → «Гринфито».
 *
 * Работает только когда все буквы заглавные. Иначе написание автора не трогаем:
 * иначе «ЛБренд» стал бы «Лбренд», а «Риф и Ко» — «Риф И Ко».
 */
function titleCase(text: string): string {
  return text
    .split(" ")
    .map((word, index) => {
      const lower = word.toLocaleLowerCase("ru");
      if (index > 0 && SMALL_WORDS.has(lower)) return lower;
      // Дефисные части тоже с большой: «две-линии» → «Две-Линии».
      return lower.replace(/(^|-)(\p{L})/gu, (_match, before: string, char: string) => before + char.toLocaleUpperCase("ru"));
    })
    .join(" ");
}

/**
 * Ядро имени поставщика: без форм юрлица, кавычек, ИНН, адресов и телефонов.
 *
 *   cleanSupplierName("ГРИНФИТО ООО")                     → "Гринфито"
 *   cleanSupplierName('ООО "ПКФ "ДВЕ ЛИНИИ"')             → "Две Линии"
 *   cleanSupplierName("Риф и Ко")                         → "Риф и Ко"
 *   cleanSupplierName("ООО Ромашка, ИНН 2224031168, …")   → "Ромашка"
 *
 * Функция идемпотентна: повторный вызов уже очищенное имя не меняет. Если после
 * чистки не осталось ничего (поставщик назван просто «ООО»), возвращаем
 * исходную строку: показать человеку «ООО» полезнее, чем пустоту.
 */
export function cleanSupplierName(raw: string): string {
  const source = typeof raw === "string" ? raw : String(raw ?? "");
  const trimmed = source.replace(/\s+/g, " ").trim();
  if (!trimmed) return "";

  const at = requisitesStart(trimmed);
  let text = at === -1 ? trimmed : trimmed.slice(0, at);

  text = text.replace(/[«»„“”"'`]/g, " ");
  text = text.replace(SHEET_TRUNCATION, " ");
  text = text.replace(ADDRESS_PART, " ");
  text = text.replace(TRAILING_INITIALS, "");
  text = removeWords(text, FULL_FORMS);
  text = removeWords(text, ABBREVIATIONS);
  text = tidy(text);

  if (!text) return trimmed;
  return isShouty(text) ? titleCase(text) : text;
}

/**
 * Ключ сравнения написаний: по нему справочник понимает, что «ГРИНФИТО ООО»,
 * «Гринфито» и строка с ИНН — один и тот же поставщик.
 */
export function supplierNameKey(raw: string): string {
  const core = cleanSupplierName(raw);
  const key = core
    .replace(/ё/giu, "е")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();

  // Только шум и остался: ключом делаем исходную строку, иначе все такие
  // поставщики слились бы в один пустой ключ.
  return key || raw.trim().replace(/\s+/g, " ").toLowerCase();
}

/**
 * Совпадают ли написания как текст: регистр, «ё», пробелы и знаки не важны.
 *
 * В отличие от `supplierNameKey` формы юрлица здесь ЗНАЧИМЫ: «Две Линии» и
 * «ПКФ Две Линии» — разные написания одного поставщика, и второе должно
 * уцелеть в алиасах, а не потеряться.
 */
export function sameSpelling(a: string, b: string): boolean {
  return flatten(a) === flatten(b);
}

function flatten(value: string): string {
  return value
    .replace(/ё/giu, "е")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

/** Есть ли в имени мусор: форма юрлица, ИНН, адрес, телефон, обрывок листа. */
export function hasSupplierNoise(raw: string): boolean {
  return NOISE.test(typeof raw === "string" ? raw : String(raw ?? ""));
}